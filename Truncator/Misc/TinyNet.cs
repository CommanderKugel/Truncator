    public static unsafe int Forward(Span<int> input_i32)
    {
        var input = stackalloc float[INPUT_SIZE];
        var acc = stackalloc float[L1_SIZE];
        var step = Vector<float>.Count;

        fixed (int* in_i32 = input_i32)
